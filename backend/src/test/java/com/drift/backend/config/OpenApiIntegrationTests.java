package com.drift.backend.config;

import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.get;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.jsonPath;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.status;

import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.boot.webmvc.test.autoconfigure.AutoConfigureMockMvc;
import org.springframework.test.context.ActiveProfiles;
import org.springframework.test.web.servlet.MockMvc;

import com.drift.backend.account.exception.SessionEndedException;
import com.drift.backend.shipment.exception.ShipmentDetailForbiddenException;

@SpringBootTest
@AutoConfigureMockMvc
@ActiveProfiles("test")
class OpenApiIntegrationTests {

	@Autowired MockMvc mvc;

	@Test
	void swaggerUiAndOpenApiDocumentTheProtectedShipmentEndpoint() throws Exception {
		mvc.perform(get("/swagger-ui/index.html"))
				.andExpect(status().isOk());

		mvc.perform(get("/v3/api-docs"))
				.andExpect(status().isOk())
				.andExpect(jsonPath("$.paths['/api/shipments'].post.summary").value("Create a shipment"))
				.andExpect(jsonPath("$.paths['/api/shipments'].post.security[0].bearerAuth").exists())
				.andExpect(jsonPath("$.paths['/api/shipments'].get.summary").value("List shipments"))
				.andExpect(jsonPath("$.paths['/api/shipments'].get.security[0].bearerAuth").exists())
				.andExpect(jsonPath("$.paths['/api/shipments'].get.parameters[?(@.name == 'reference')].description")
						.value(org.hamcrest.Matchers.hasItem(org.hamcrest.Matchers.containsString("substring"))))
				.andExpect(jsonPath("$.paths['/api/shipments'].get.parameters[?(@.name == 'vessel')].description")
						.value(org.hamcrest.Matchers.hasItem(org.hamcrest.Matchers.containsString("mother vessel or feeder vessel"))))
				.andExpect(jsonPath("$.paths['/api/shipments'].get.parameters[?(@.name == 'customer')].description")
						.value(org.hamcrest.Matchers.hasItem(org.hamcrest.Matchers.containsString("linked importer"))))
				.andExpect(jsonPath("$.paths['/api/shipments'].get.parameters[?(@.name == 'arrivalDate')].schema.format").value("date"))
				.andExpect(jsonPath("$.paths['/api/shipments'].get.parameters[?(@.name == 'status')].schema.enum")
						.value(org.hamcrest.Matchers.hasItem(org.hamcrest.Matchers.contains("ACTIVE", "ARCHIVED"))))
				.andExpect(jsonPath("$.paths['/api/shipments'].get.responses['400']").exists())
				.andExpect(jsonPath("$.paths['/api/shipments/{shipmentId}'].get.summary").value("Get a shipment"))
				.andExpect(jsonPath("$.paths['/api/shipments/{shipmentId}'].get.description")
						.value("Returns one shipment visible to the authenticated user's active company, including a shipment linked to that company as the importer, and includes the planned connection window calculated from the stored mother-vessel arrival and feeder-vessel departure, the remaining connection window from the mother vessel's estimated arrival when that estimate can be used, and the latest retained AIS position for each vessel name. Risk uses the remaining window when the estimate can be used, and otherwise the planned window. The same read includes the evidence, the assumptions, and the confidence for that risk. They are calculated when the shipment is read and are not stored. An assessment with no risk names the missing planned time and does not include a limited confidence. A shipment of another company is forbidden, and an unknown id is reported as not found."))
				.andExpect(jsonPath("$.paths['/api/shipments/{shipmentId}'].get.responses['403'].content['application/json'].schema.properties.message.type")
						.value("string"))
				.andExpect(jsonPath("$.paths['/api/shipments/{shipmentId}'].get.responses['403'].content['application/json'].examples['Shipment of another company'].value.message")
						.value(ShipmentDetailForbiddenException.MESSAGE))
				.andExpect(jsonPath("$.paths['/api/shipments/{shipmentId}'].get.responses['404'].content['application/json'].schema.properties.message.type")
						.value("string"))
				.andExpect(jsonPath("$.paths['/api/shipments/{shipmentId}'].put.summary").value("Replace a shipment"))
				.andExpect(jsonPath("$.paths['/api/shipments/{shipmentId}'].put.security[0].bearerAuth").exists())
				.andExpect(jsonPath("$.paths['/api/shipments/{shipmentId}'].put.responses['200'].content['application/json'].schema.$ref")
						.value("#/components/schemas/ShipmentResponse"))
				.andExpect(jsonPath("$.paths['/api/shipments/{shipmentId}'].put.responses['409']").exists())
				.andExpect(jsonPath("$.components.schemas.UpdateShipmentRequest.required").isArray())
				.andExpect(jsonPath("$.components.schemas.UpdateShipmentRequest.properties.version.description")
						.value(org.hamcrest.Matchers.containsString("version")))
				.andExpect(jsonPath("$.components.securitySchemes.bearerAuth.type").value("http"))
				.andExpect(jsonPath("$.components.securitySchemes.bearerAuth.scheme").value("bearer"))
				.andExpect(jsonPath("$.components.schemas.CreateShipmentRequest.required").isArray())
				.andExpect(jsonPath("$.components.schemas.CreateShipmentRequest.properties.shipmentReference.example")
						.value("HBL-2026-001"))
				.andExpect(jsonPath("$.paths['/api/shipments/{shipmentId}'].get.responses['200'].content['application/json'].schema.$ref")
						.value("#/components/schemas/ShipmentDetailResponse"))
				.andExpect(jsonPath("$.components.schemas.ShipmentDetailResponse.properties.connectionWindow.$ref")
						.value("#/components/schemas/ConnectionWindow"))
				.andExpect(jsonPath("$.components.schemas.ShipmentDetailResponse.properties.remainingConnectionWindow.$ref")
						.value("#/components/schemas/RemainingConnectionWindow"))
				.andExpect(jsonPath("$.components.schemas.ShipmentDetailResponse.properties.risk.description")
						.value(org.hamcrest.Matchers.containsString("remaining connection window")))
				.andExpect(jsonPath("$.components.schemas.ShipmentDetailResponse.properties.assessmentExplanation.$ref")
						.value("#/components/schemas/AssessmentExplanation"))
				.andExpect(jsonPath("$.components.schemas.AssessmentExplanation.properties.confidence.example")
						.value("The estimated arrival was used."))
				.andExpect(jsonPath("$.components.schemas.AssessmentExplanation.description")
						.value(org.hamcrest.Matchers.containsString("not stored")))
				.andExpect(jsonPath("$.components.schemas.ShipmentResponse.properties.assessmentExplanation").doesNotExist())
				.andExpect(jsonPath("$.components.schemas.ShipmentRisk.description")
						.value(org.hamcrest.Matchers.containsString("remaining connection window")))
				.andExpect(jsonPath("$.components.schemas.RemainingConnectionWindow.properties.duration.example")
						.value("6 hours"))
				.andExpect(jsonPath("$.components.schemas.RemainingConnectionWindow.properties.missedBy.example")
						.value("2 hours"))
				.andExpect(jsonPath("$.components.schemas.ShipmentResponse.properties.remainingConnectionWindow").doesNotExist())
				.andExpect(jsonPath("$.components.schemas.ShipmentResponse.properties.risk").doesNotExist())
				.andExpect(jsonPath("$.components.schemas.ShipmentDetailResponse.properties.version.type").value("integer"))
				.andExpect(jsonPath("$.components.schemas.ShipmentDetailResponse.properties.motherVesselPosition.$ref")
						.value("#/components/schemas/VesselPosition"))
				.andExpect(jsonPath("$.components.schemas.ShipmentDetailResponse.properties.feederVesselPosition.$ref")
						.value("#/components/schemas/VesselPosition"))
				.andExpect(jsonPath("$.components.schemas.ShipmentDetailResponse.properties.motherVesselImo").exists())
				.andExpect(jsonPath("$.components.schemas.ShipmentDetailResponse.properties.motherVesselMmsi").exists())
				.andExpect(jsonPath("$.components.schemas.ShipmentDetailResponse.properties.motherVesselOperator").exists())
				.andExpect(jsonPath("$.components.schemas.ShipmentDetailResponse.properties.feederVesselImo").exists())
				.andExpect(jsonPath("$.components.schemas.ShipmentDetailResponse.properties.feederVesselMmsi").exists())
				.andExpect(jsonPath("$.components.schemas.ShipmentDetailResponse.properties.feederVesselOperator").exists())
				.andExpect(jsonPath("$.components.schemas.ShipmentDetailResponse.properties.motherVesselNameWarning").exists())
				.andExpect(jsonPath("$.components.schemas.ShipmentDetailResponse.properties.feederVesselNameWarning").exists())
				.andExpect(jsonPath("$.components.schemas.ShipmentResponse.properties.motherVesselImo").doesNotExist())
				.andExpect(jsonPath("$.components.schemas.ShipmentResponse.properties.motherVesselNameWarning").doesNotExist())
				.andExpect(jsonPath("$.components.schemas.CreateShipmentRequest.properties.motherVesselImo").exists())
				.andExpect(jsonPath("$.components.schemas.UpdateShipmentRequest.properties.feederVesselOperator").exists())
				.andExpect(jsonPath("$.components.schemas.ShipmentResponse.properties.motherVesselPosition").doesNotExist())
				.andExpect(jsonPath("$.components.schemas.ShipmentResponse.properties.version.type").value("integer"))
				.andExpect(jsonPath("$.components.schemas.ShipmentResponse.properties.connectionWindow.$ref")
						.value("#/components/schemas/ConnectionWindow"))
				.andExpect(jsonPath("$.components.schemas.ConnectionWindow.properties.duration.example")
						.value("1 day 4 hours"))
				.andExpect(jsonPath("$.components.schemas.ConnectionWindow.properties.totalSeconds.example")
						.value("100800"))
				.andExpect(jsonPath("$.paths['/api/shipments'].get.responses['401'].content['application/json'].example.message")
						.value(SessionEndedException.MESSAGE))
				.andExpect(jsonPath("$.paths['/api/shipments'].post.responses['401'].content['application/json'].example.message")
						.value(SessionEndedException.MESSAGE))
				.andExpect(jsonPath("$.paths['/api/shipments/{shipmentId}'].get.responses['401'].content['application/json'].example.message")
						.value(SessionEndedException.MESSAGE))
				.andExpect(jsonPath("$.paths['/api/shipments/{shipmentId}/tracking'].get.summary")
						.value("Get shipment vessel tracking"))
				.andExpect(jsonPath("$.paths['/api/shipments/{shipmentId}/tracking'].get.security[0].bearerAuth").exists())
				.andExpect(jsonPath("$.paths['/api/shipments/{shipmentId}/tracking'].get.responses['200'].content['application/json'].schema.$ref")
						.value("#/components/schemas/ShipmentTrackingResponse"))
				.andExpect(jsonPath("$.components.schemas.ShipmentTrackingResponse.properties.motherVessel.type")
						.value(org.hamcrest.Matchers.contains("object", "null")))
				.andExpect(jsonPath("$.components.schemas.ShipmentTrackingResponse.properties.motherVessel.$ref")
						.value("#/components/schemas/VesselPosition"))
				.andExpect(jsonPath("$.components.schemas.ShipmentTrackingResponse.properties.feederVessel.type")
						.value(org.hamcrest.Matchers.contains("object", "null")))
				.andExpect(jsonPath("$.components.schemas.ShipmentTrackingResponse.properties.feederVessel.$ref")
						.value("#/components/schemas/VesselPosition"))
				.andExpect(jsonPath("$.components.schemas.ShipmentTrackingResponse.properties.motherVesselNameWarning").exists())
				.andExpect(jsonPath("$.components.schemas.ShipmentTrackingResponse.properties.feederVesselNameWarning").exists())
				.andExpect(jsonPath("$.paths['/api/shipments/{shipmentId}/tracking'].get.responses['401'].content['application/json'].example.message")
						.value(SessionEndedException.MESSAGE))
				.andExpect(jsonPath("$.paths['/api/shipments/{shipmentId}/tracking'].get.responses['404']").exists())
				.andExpect(jsonPath("$.paths['/api/shipments/{shipmentId}/track-history'].get.summary")
						.value("Get vessel track history"))
				.andExpect(jsonPath("$.paths['/api/shipments/{shipmentId}/track-history'].get.security[0].bearerAuth").exists())
				.andExpect(jsonPath("$.paths['/api/shipments/{shipmentId}/track-history'].get.responses['200'].content['application/json'].schema.$ref")
						.value("#/components/schemas/VesselTrackResponse"))
				.andExpect(jsonPath("$.paths['/api/shipments/{shipmentId}/track-history'].get.responses['400']").exists())
				.andExpect(jsonPath("$.paths['/api/shipments/{shipmentId}/track-history'].get.responses['404']").exists())
				.andExpect(jsonPath("$.components.schemas.VesselTrackResponse.properties.points.items.$ref")
						.value("#/components/schemas/TrackPoint"))
				.andExpect(jsonPath("$.components.schemas.TrackPoint.properties.id").exists())
				.andExpect(jsonPath("$.components.schemas.ShipmentDetailResponse.properties.importer.$ref")
						.value("#/components/schemas/Organisation"))
				.andExpect(jsonPath("$.paths['/api/shipments/{shipmentId}/link-importer'].patch.summary")
						.value("Link a shipment to an importer"))
				.andExpect(jsonPath("$.paths['/api/shipments/{shipmentId}/link-importer'].patch.security[0].bearerAuth").exists())
				.andExpect(jsonPath("$.paths['/api/shipments/{shipmentId}/link-importer'].patch.responses['200'].content['application/json'].schema.$ref")
						.value("#/components/schemas/ShipmentDetailResponse"))
				.andExpect(jsonPath("$.paths['/api/shipments/{shipmentId}/link-importer'].patch.responses['400'].content['application/json'].example.message")
						.value(com.drift.backend.shipment.exception.InvalidImporterOrganisationException.MESSAGE))
				.andExpect(jsonPath("$.paths['/api/shipments/{shipmentId}/link-importer'].patch.responses['401'].content['application/json'].example.message")
						.value(SessionEndedException.MESSAGE))
				.andExpect(jsonPath("$.paths['/api/shipments/{shipmentId}/link-importer'].patch.responses['404']").exists())
				.andExpect(jsonPath("$.paths['/api/shipments/import'].post.summary").value("Start a shipment CSV import"))
				.andExpect(jsonPath("$.paths['/api/shipments/import'].post.responses['202']").exists())
				.andExpect(jsonPath("$.paths['/api/shipments/import/{jobId}'].get.summary").value("Get shipment import status"))
				.andExpect(jsonPath("$.paths['/api/shipments/import/{jobId}/errors'].get.summary").value("Get shipment import row errors"));
	}
}
