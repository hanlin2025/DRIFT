-- Append-only history of accepted recommendation decisions.
-- Main's V31 creates maritime snapshot observations. CDG-252's V32 widens
-- maritime AI validation status and must be applied before this V33 migration.
-- V29 creates recommendation_decisions and V30 creates shipment importer constraints.
-- Existing current rows are copied once. Their stored actor and decided_at are kept.
-- The actor name is the user's name at migration time, because earlier decisions did not store one.
-- Decisions already replaced on recommendation_decisions are not reconstructed.
-- recommendation_decisions is not updated.

CREATE TABLE recommendation_decision_history (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	shipment_id BIGINT NOT NULL REFERENCES shipments(id) ON DELETE CASCADE,
	outcome VARCHAR(16) NOT NULL,
	recommendation_name VARCHAR(100) NOT NULL,
	recommendation_wording TEXT NOT NULL,
	selected_response_name VARCHAR(100),
	selected_response_wording TEXT,
	decided_by_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
	decided_by_name VARCHAR(200) NOT NULL,
	decided_at TIMESTAMPTZ NOT NULL,
	CONSTRAINT recommendation_decision_history_outcome_check
		CHECK (outcome IN ('APPROVED', 'MODIFIED', 'DISMISSED')),
	CONSTRAINT recommendation_decision_history_recommendation_text_check
		CHECK (char_length(btrim(recommendation_name)) > 0
			AND char_length(btrim(recommendation_wording)) > 0),
	CONSTRAINT recommendation_decision_history_selected_check
		CHECK (
			(outcome IN ('APPROVED', 'DISMISSED')
				AND selected_response_name IS NULL
				AND selected_response_wording IS NULL)
			OR (outcome = 'MODIFIED'
				AND selected_response_name IS NOT NULL
				AND selected_response_wording IS NOT NULL
				AND char_length(btrim(selected_response_name)) > 0
				AND char_length(btrim(selected_response_wording)) > 0
				AND btrim(selected_response_name) <> btrim(recommendation_name))
		),
	CONSTRAINT recommendation_decision_history_actor_name_check
		CHECK (char_length(btrim(decided_by_name)) > 0)
);

CREATE INDEX recommendation_decision_history_shipment_order_idx
	ON recommendation_decision_history (shipment_id, decided_at DESC, id DESC);

CREATE INDEX recommendation_decision_history_decided_by_user_idx
	ON recommendation_decision_history (decided_by_user_id);

INSERT INTO recommendation_decision_history (
	shipment_id,
	outcome,
	recommendation_name,
	recommendation_wording,
	selected_response_name,
	selected_response_wording,
	decided_by_user_id,
	decided_by_name,
	decided_at
)
SELECT
	decision.shipment_id,
	decision.outcome,
	decision.recommendation_name,
	decision.recommendation_wording,
	decision.selected_response_name,
	decision.selected_response_wording,
	decision.decided_by_user_id,
	actor.full_name,
	decision.decided_at
FROM recommendation_decisions AS decision
JOIN users AS actor ON actor.id = decision.decided_by_user_id;
