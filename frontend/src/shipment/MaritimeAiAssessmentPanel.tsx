import { type MaritimeAiAssessment } from './api';

function formatScheduleFact(fact: NonNullable<MaritimeAiAssessment['deterministicSummary']>['shipmentScheduleFacts'][number]) {
  return [fact.subject, fact.eventType, fact.timestamp].filter(Boolean).join(' · ') || 'Schedule information is not available.';
}

function isVerifiedCaptureReplay(assessment: MaritimeAiAssessment) {
  return assessment.provider === 'openai-responses (verified capture replay)';
}

export function MaritimeAiAssessmentPanel({ assessments, unavailable, generating, onGenerate }: {
  assessments: MaritimeAiAssessment[];
  unavailable: boolean;
  generating: boolean;
  onGenerate: () => void;
}) {
  if (unavailable) return <section className="notice" aria-label="AI maritime interpretation">AI maritime interpretation is unavailable. Maritime evidence remains available.</section>;
  if (assessments.length === 0) return <section className="notice" aria-label="AI maritime interpretation">
    <p>No AI maritime interpretation has been generated for this shipment.</p>
    <button type="button" onClick={onGenerate} disabled={generating}>{generating ? 'Generating advisory…' : 'Generate AI maritime interpretation'}</button>
  </section>;
  const assessment = assessments[0];
  return <section className="shipment-record maritime-context" aria-label="AI maritime interpretation">
    <p className="eyebrow">MARITIME ASSESSMENT</p>
    <p><strong>Assessment status</strong>{assessment.state} · validation {assessment.validationStatus} · generated {assessment.generatedAtUtc ?? 'not recorded'}</p>
    {isVerifiedCaptureReplay(assessment) && <p className="notice">This is a verified OpenAI provider-capture replay for local demonstration. No provider request was made when this record was persisted.</p>}
    {assessment.deterministicSummary && <section aria-label="Shipment schedule and source evidence">
      <p><strong>Shipment schedule &amp; source evidence</strong></p>
      {assessment.deterministicSummary.shipmentScheduleFacts.map((fact, index) => <p key={`schedule-${index}`}>{formatScheduleFact(fact)}</p>)}
    </section>}
    {assessment.state === 'GENERATED' && assessment.interpretation ? <>
      <p><strong>What changed</strong>{assessment.interpretation.claims.map(claim => claim.statement).join(' ')}</p>
      <p><strong>Why it matters</strong>{assessment.interpretation.summary}</p>
      <p><strong>Uncertainty</strong>{assessment.interpretation.uncertainties.length ? assessment.interpretation.uncertainties.join(' ') : 'No additional uncertainty was recorded.'}</p>
      <p><strong>Recommended next checks</strong>{assessment.interpretation.followUpConsiderations.length ? assessment.interpretation.followUpConsiderations.join(' ') : 'Review the current vessel and port information before making an operational decision.'}</p>
    </> : <p>{assessment.limitation ?? 'The model did not produce a validated interpretation.'}</p>}
    <details>
      <summary>Assessment and evidence details</summary>
      <p>Provider: {assessment.provider || 'not configured'} · model: {assessment.model || 'not recorded'} · prompt: {assessment.promptVersion}.</p>
      {assessment.provider === 'controlled-replay-stub' && <p>This assessment was generated by the controlled offline stub from fictional evidence; it is not an external AI-provider response.</p>}
      {assessment.deterministicSummary?.evidenceFacts.map((fact, index) => <section key={`evidence-${index}`} aria-label={`Evidence ${fact.evidenceId ?? index}`}>
        <p><strong>{fact.evidenceId ?? 'No evidence ID'}</strong> · {fact.sourceType} · {fact.sourceMode} · {fact.associationScope}</p>
        <p>Source event: {fact.timestamp ?? 'not recorded'} · observed: {fact.observedAt ?? 'not recorded'} · retrieved: {fact.retrievedAtUtc ?? 'not recorded'}</p>
        <p>Citation: {fact.citation} · canonical reference: {fact.factReference}</p>
      </section>)}
      {assessment.deterministicSummary?.limitations.length ? <section aria-label="Evidence limitations"><p><strong>Evidence limitations</strong></p><ul>{assessment.deterministicSummary.limitations.map((limitation, index) => <li key={index}>{limitation}</li>)}</ul></section> : null}
      {assessment.interpretation?.claims.map((claim, index) => <section key={`claim-${index}`} aria-label={`Grounding for claim ${index + 1}`}><p>Evidence IDs: {claim.evidenceIds.join(', ')} · relationship {claim.relationshipType ?? 'none'} · applicability {claim.applicability}</p><p>Canonical references: {claim.factReferences?.join(', ') || 'none'}</p></section>)}
      <p>This advisory does not change shipment timing, risk, alerts, recommendations, or operational actions.</p>
    </details>
    <button type="button" onClick={onGenerate} disabled={generating}>{generating ? 'Generating advisory…' : 'Generate new interpretation'}</button>
  </section>;
}
